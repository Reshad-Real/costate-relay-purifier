"""Write manuscript/generated/fallback.tex with a ?? placeholder (providecommand) for every
generated-number macro used in main.tex but not defined in macros.tex, so a missing result shows
as ?? in the PDF instead of breaking the build."""
import os, re

BS = chr(92)  # backslash
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
tex = ""
for rel in [("manuscript2", "main.tex"), ("manuscript2", "supplement.tex"), ("manuscript2", "response.tex")]:
    p = os.path.join(ROOT, *rel)
    if os.path.exists(p):
        tex += open(p, encoding="utf-8").read()
mac = open(os.path.join(ROOT, "manuscript", "generated", "macros.tex"), encoding="utf-8").read()
defined = set(re.findall(re.escape(BS + "newcommand{" + BS) + r"([A-Za-z]+)\}", mac))
# candidate macros: names starting lower-case and containing an upper-case letter (camelCase)
used = set(re.findall(re.escape(BS) + r"([a-z][A-Za-z]*[A-Z][A-Za-z]*)", tex))
std = {"bibliographystyle", "biboptions", "usepackage", "graphicspath", "usetikzlibrary", "captionsetup",
       "newtheorem", "newcommand", "renewcommand", "includegraphics", "textbf", "mathbf", "mathcal", "mathbb",
       "mathrm", "operatorname", "linenumbers", "textwidth", "linewidth", "bottomrule", "toprule", "midrule",
       "hfill", "noindent", "providecommand", "textit", "underline", "textsuperscript", "textsubscript",
       "appendix", "bibliography"}
missing = sorted(u for u in used if u not in std and u not in defined)
with open(os.path.join(ROOT, "manuscript", "generated", "fallback.tex"), "w") as f:
    f.write("% generated by code/analysis/fallbacks.py\n")
    for u in missing:
        f.write(BS + "providecommand{" + BS + u + "}{" + BS + "textbf{??}}\n")
print("missing macros:", missing)
