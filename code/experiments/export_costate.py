"""Export costate-law parameters to C (csolver/costate_params.h) and check the C implementation against
the Python controller on random states (csolver/test_costate.c)."""
import os, sys, json, subprocess
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import numpy as np
from aqmpc.params import Plant, MPCSettings, NP, NZ, C_BOUND
from aqmpc.controllers import CostateFeedback
from common import RES

NL = chr(10)
CDIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "csolver")


def cf32(v):
    t = f"{float(v):.9g}"
    return (t if any(ch in t for ch in ".en") else t + ".0") + "f"


def carr(a):
    a = np.asarray(a, dtype=np.float64)
    if a.ndim == 1:
        return "{" + ", ".join(cf32(v) for v in a) + "}"
    return "{" + ", ".join(carr(r) for r in a) + "}"


if __name__ == "__main__":
    tun = json.load(open(os.path.join(RES, "tuning.json")))
    pl = Plant()
    st = MPCSettings(rho=tun["rho_iso"])
    cf = CostateFeedback(pl, st)
    lines = ["/* generated by experiments/export_costate.py - nominal model, rho tuned to the relay energy */",
             "#pragma once", '#include "costate_law.h"',
             "static const costate_params_t COSTATE_PARAMS = {",
             f"  {carr(cf.Minv_T)},", f"  {carr(cf.M1)},", f"  {carr(cf.W)},", f"  {carr(C_BOUND)},",
             f"  {cf32(st.M)}, {cf32(st.rho)}, {cf32(pl.fan.p_fan)}, {cf32(pl.fan.p_exp)},",
             f"  {carr(st.duties)}", "};"]
    open(os.path.join(CDIR, "costate_params.h"), "w").write(NL.join(lines) + NL)
    # random test states spanning clean to heavily polluted conditions
    rng = np.random.default_rng(5)
    base = np.array([40, 80, 300, 600, 1.0, 30.0])[:, None] * np.ones((1, NZ))
    X = base[None] * np.exp(rng.normal(0, 1.0, (2000, NP, NZ)))
    occ = rng.integers(0, 2, 2000).astype(float)
    rhos = np.exp(rng.uniform(np.log(0.003), np.log(0.3), 2000))
    exp = []
    for x, o, r in zip(X, occ, rhos):
        w = cf.W * o + st.M * (x > cf.cb) / cf.cb
        lam = np.einsum("pij,pj->pi", cf.Minv_T, w)
        B = -np.einsum("pi,pij,pj->", lam, cf.M1, x)
        cost = r * pl.fan.p_fan * st.duties ** pl.fan.p_exp - st.duties * B
        exp.append(int(np.argmin(cost)))
    np.savetxt(os.path.join(CDIR, "costate_cases.txt"),
               np.column_stack([occ, rhos, X.reshape(2000, -1), exp]), fmt="%.9g")
    test = r'''#include <stdio.h>
#include "costate_params.h"
int main(void) {
    FILE *f = fopen("costate_cases.txt", "r"); int n = 0, bad = 0;
    float occ, rho, e, x[CS_NP][CS_NZ];
    while (fscanf(f, "%f %f", &occ, &rho) == 2) {
        for (int p = 0; p < CS_NP; ++p) for (int j = 0; j < CS_NZ; ++j) fscanf(f, "%f", &x[p][j]);
        fscanf(f, "%f", &e);
        int u = costate_duty(&COSTATE_PARAMS, (const float (*)[CS_NZ])x, occ, rho);
        if (u != (int)e) bad++;
        n++;
    }
    printf("%d cases, %d mismatches\n", n, bad);
    return 0;
}
'''
    open(os.path.join(CDIR, "test_costate.c"), "w").write(test)
    exe = os.path.join(CDIR, "test_costate.exe")
    subprocess.run(["gcc", "-O2", "-std=c99", "-Wall", "-o", exe, os.path.join(CDIR, "test_costate.c"), "-lm"],
                   check=True, cwd=CDIR)
    r = subprocess.run([exe], capture_output=True, text=True, cwd=CDIR)
    print(r.stdout.strip())
    os.makedirs(os.path.join(RES, "e6"), exist_ok=True)
    json.dump({"result": r.stdout.strip()}, open(os.path.join(RES, "e6", "costate_c_check.json"), "w"))
