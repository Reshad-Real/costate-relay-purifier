"""Export the rollout costate law (Eq. (11)) to C (csolver/rollout_params.h) and check the C implementation
(csolver/rollout_law.h) against the Python controller's decision rule on random states, drives, steps and budgets
(csolver/test_rollout.c). Writes results/e6/rollout_c_check.json."""
import os, sys, json, subprocess
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import numpy as np
from aqmpc.params import Plant, MPCSettings, NP, NZ
from aqmpc.extra_controllers import RolloutCostate
from common import RES
from export_costate import cf32, carr

NL = chr(10)
CDIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "csolver")
N = 3000


def py_decision(rc, x, d, k, rem):
    """The decision of RolloutCostate.act for a given state estimate, drive estimate, step and remaining budget."""
    dt = rc.s.dt
    C1 = np.einsum("upij,pj->upi", rc.disc.A, x) + np.einsum("upij,pj->upi", rc.disc.G, d)
    wgt = rc.o[k + 1] * dt * rc.W + rc.Lam[k + 1]
    cost = rc.s.rho * rc.pcost * dt + np.einsum("upz,pz->u", C1, wgt)
    cost = cost + rc.M * (np.maximum(C1 - rc.cb, 0.0) / rc.cb).sum(axis=(1, 2)) * dt
    cost = np.where(rc.pcost * dt <= rem + 1e-12, cost, np.inf)
    return int(np.argmin(cost)), cost


if __name__ == "__main__":
    tun = json.load(open(os.path.join(RES, "tuning.json")))
    pl = Plant()
    st = MPCSettings(rho=tun["rho_iso"])
    rc = RolloutCostate(pl, st)
    Ab, _ = rc.disc.mats(rc.u_base)
    on = np.flatnonzero(rc.o > 0)
    k_on, k_off = int(on[0]), int(on[-1]) + 1
    assert np.all(rc.o[k_on:k_off] == 1) and rc.o.sum() == k_off - k_on
    lines = ["/* generated by experiments/export_rollout.py - nominal model, rho tuned to the relay energy */",
             "#pragma once", '#include "rollout_law.h"',
             "static const rollout_params_t ROLLOUT_PARAMS = {",
             f"  {carr(rc.disc.A)},", f"  {carr(rc.disc.G)},", f"  {carr(Ab)},", f"  {carr(rc.W)},",
             f"  {carr(st.bound)},", f"  {cf32(rc.M)}, {cf32(st.rho)}, {cf32(st.dt)},",
             f"  {carr(rc.pcost)},", f"  {rc.K}, {k_on}, {k_off}", "};"]
    open(os.path.join(CDIR, "rollout_params.h"), "w").write(NL.join(lines) + NL)
    # random cases: clean to heavily polluted states, drives of the same order as the removal flux, all steps,
    # unconstrained and nearly exhausted budgets
    rng = np.random.default_rng(7)
    base = np.array([40, 80, 300, 600, 1.0, 30.0])[:, None] * np.ones((1, NZ))
    X = base[None] * np.exp(rng.normal(0, 1.0, (N, NP, NZ)))
    D = base[None] * np.exp(rng.normal(0, 1.0, (N, NP, NZ))) * rng.uniform(0.0, 3.0, (N, 1, 1))
    K = rng.integers(0, rc.K, N)
    pmax = rc.pcost.max() * st.dt
    R = np.where(rng.random(N) < 0.5, 1e9, rng.uniform(0, 1.2 * pmax, N))
    exp, margin = [], []
    for x, d, k, r in zip(X, D, K, R):
        u, cost = py_decision(rc, x, d, int(k), r)
        exp.append(u)
        c = np.sort(cost[np.isfinite(cost)])
        margin.append((c[1] - c[0]) / max(abs(c[0]), 1e-12) if len(c) > 1 else np.inf)
    np.savetxt(os.path.join(CDIR, "rollout_cases.txt"),
               np.column_stack([K, R, X.reshape(N, -1), D.reshape(N, -1), exp]), fmt="%.9g")
    test = r'''#include <stdio.h>
#include <math.h>
#include "rollout_params.h"
int main(void) {
    FILE *f = fopen("rollout_cases.txt", "r"); int n = 0, bad = 0;
    float kf, rem, e, x[RL_NP][RL_NZ], d[RL_NP][RL_NZ];
    while (fscanf(f, "%f %f", &kf, &rem) == 2) {
        for (int p = 0; p < RL_NP; ++p) for (int j = 0; j < RL_NZ; ++j) fscanf(f, "%f", &x[p][j]);
        for (int p = 0; p < RL_NP; ++p) for (int j = 0; j < RL_NZ; ++j) fscanf(f, "%f", &d[p][j]);
        fscanf(f, "%f", &e);
        int u = rollout_duty(&ROLLOUT_PARAMS, (const float (*)[RL_NZ])x, (const float (*)[RL_NZ])d, (int)kf, rem);
        if (u != (int)e) { bad++; printf("mismatch case %d: C %d, Python %d\n", n, u, (int)e); }
        n++;
    }
    printf("%d cases, %d mismatches\n", n, bad);
    return 0;
}
'''
    open(os.path.join(CDIR, "test_rollout.c"), "w").write(test)
    exe = os.path.join(CDIR, "test_rollout.exe")
    subprocess.run(["gcc", "-O2", "-std=c99", "-Wall", "-o", exe, os.path.join(CDIR, "test_rollout.c"), "-lm"],
                   check=True, cwd=CDIR)
    r = subprocess.run([exe], capture_output=True, text=True, cwd=CDIR)
    out = r.stdout.strip().splitlines()
    print(NL.join(out[-6:]))
    bad = [int(l.split()[2].rstrip(":")) for l in out if l.startswith("mismatch")]
    margin = np.array(margin)
    res = {"cases": N, "mismatches": len(bad), "decisions": np.bincount(exp, minlength=len(st.duties)).tolist(),
           "max_rel_margin_at_mismatch": float(margin[bad].max()) if bad else None,
           "budget_limited_cases": int((R < 1e8).sum()), "K": rc.K, "k_on": k_on, "k_off": k_off,
           "macs_backward_max": int(rc.K * NP * NZ * NZ), "macs_scoring": int(len(st.duties) * NP * NZ * 2 * NZ)}
    os.makedirs(os.path.join(RES, "e6"), exist_ok=True)
    json.dump(res, open(os.path.join(RES, "e6", "rollout_c_check.json"), "w"), indent=1)
    print(res)
