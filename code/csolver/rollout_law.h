/* Rollout costate law (manuscript Eq. (11)) for the CCU firmware - portable C99, float.
 *
 *   u_k = argmin_{u in U, P(u) dt <= R_k}  rho P(u) dt + sum_p (o_{k+1} dt W_p + Lam_{p,k+1})^T c_{p,k+1}(u)
 *                                           + M pen(c_{k+1}(u)) dt,
 *   c_{p,k+1}(u) = A_p(u) x_p + G_p(u) d_p,
 *   Lam_{p,j} = Ab_p^T (o_{j+1} dt W_p + Lam_{p,j+1}),  Lam_{p,K} = 0,  Ab_p = A_p(u_base).
 *
 * The costate Lam_{k+1} is recomputed backward from the end of the day at every decision, so no table is stored;
 * this costs at most K * NP * NZ^2 multiply-adds. x is the interval-averaged zone concentration, d the drive
 * estimate, rem the remaining energy budget in Wh (INFINITY without a budget).
 * Parameters are generated by experiments/export_rollout.py into rollout_params.h.
 */
#ifndef ROLLOUT_LAW_H
#define ROLLOUT_LAW_H
#include <string.h>

#ifndef RL_NP
#define RL_NP 6
#endif
#ifndef RL_NZ
#define RL_NZ 3
#endif
#ifndef RL_NU
#define RL_NU 4
#endif

typedef struct {
    float A[RL_NU][RL_NP][RL_NZ][RL_NZ];   /* discrete transition at each duty */
    float G[RL_NU][RL_NP][RL_NZ][RL_NZ];   /* discrete drive input at each duty */
    float Ab[RL_NP][RL_NZ][RL_NZ];         /* transition at the base duty */
    float W[RL_NP][RL_NZ];                 /* exposure-index weights */
    float cb[RL_NP];                       /* soft bounds */
    float M, rho, dt;                      /* penalty, economic weight, step (h) */
    float pcost[RL_NU];                    /* modelled fan power at each duty, W */
    int K, k_on, k_off;                    /* steps per day; occupied for k_on <= k < k_off */
} rollout_params_t;

static inline float rl_occ(const rollout_params_t *c, int k)
{
    return (k >= c->k_on && k < c->k_off) ? 1.0f : 0.0f;
}

/* Returns the index of the selected duty at step k (0 <= k < K). */
static inline int rollout_duty(const rollout_params_t *c, const float x[RL_NP][RL_NZ], const float d[RL_NP][RL_NZ],
                               int k, float rem)
{
    float lam[RL_NP][RL_NZ], v[RL_NZ], best = 0.0f;
    int p, i, j, u, kk, iu = 0, found = 0;
    memset(lam, 0, sizeof lam);
    for (kk = c->K - 1; kk > k; --kk) {                 /* lam <- Lam_{k+1} */
        float o = rl_occ(c, kk + 1) * c->dt;
        for (p = 0; p < RL_NP; ++p) {
            for (j = 0; j < RL_NZ; ++j) v[j] = o * c->W[p][j] + lam[p][j];
            for (i = 0; i < RL_NZ; ++i) {
                float s = 0.0f;
                for (j = 0; j < RL_NZ; ++j) s += c->Ab[p][j][i] * v[j];
                lam[p][i] = s;
            }
        }
    }
    {
        float o = rl_occ(c, k + 1) * c->dt;
        for (p = 0; p < RL_NP; ++p)
            for (j = 0; j < RL_NZ; ++j) lam[p][j] += o * c->W[p][j];
    }
    for (u = 0; u < RL_NU; ++u) {
        float cost, pen = 0.0f;
        if (c->pcost[u] * c->dt > rem) continue;         /* budget filter */
        cost = c->rho * c->pcost[u] * c->dt;
        for (p = 0; p < RL_NP; ++p)
            for (i = 0; i < RL_NZ; ++i) {
                float c1 = 0.0f;
                for (j = 0; j < RL_NZ; ++j) c1 += c->A[u][p][i][j] * x[p][j] + c->G[u][p][i][j] * d[p][j];
                cost += lam[p][i] * c1;
                if (c1 > c->cb[p]) pen += (c1 - c->cb[p]) / c->cb[p];
            }
        cost += c->M * pen * c->dt;
        if (!found || cost < best) { best = cost; iu = u; found = 1; }
    }
    return iu;
}
#endif
